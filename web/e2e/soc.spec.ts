import { test, expect } from "@playwright/test";

test("analyst follows real evidence from dashboard through report", async ({ page }) => {
  const username = process.env.AEGIS_E2E_USERNAME;
  const password = process.env.AEGIS_E2E_PASSWORD;
  if (!username || !password) throw new Error("Set AEGIS_E2E_USERNAME and AEGIS_E2E_PASSWORD after running scripts/e2e_server.py");
  await page.goto("/");
  await page.getByLabel("Username", { exact: true }).fill(username);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Dashboard", exact: true })).toBeVisible();
  await expect(page.getByText("Recent alerts", { exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/dashboard.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("heading", { name: "Dashboard", exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/dashboard-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("navigation").getByRole("button", { name: "Alerts", exact: true }).click();
  await page.getByRole("button", { name: /Open Potential account compromise/ }).first().click();
  await expect(page.getByRole("heading", { name: "Why this detection fired" })).toBeVisible();
  const deepLink = page.url();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Why this detection fired" })).toBeVisible();
  expect(page.url()).toBe(deepLink);
  await page.getByRole("tab", { name: "Evidence", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Source evidence" })).toBeVisible();
  await page.locator("details.evidence summary").first().click();
  await expect(page.getByText(/SHA-256/).first()).toBeVisible();
  await page.getByRole("tab", { name: "AI Analysis", exact: true }).click();
  await page.getByRole("button", { name: "Analyze evidence", exact: true }).click();
  await expect(page.getByText(/DETERMINISTIC EVIDENCE SUMMARY/)).toBeVisible();
  await page.getByRole("navigation").getByRole("button", { name: "Incidents", exact: true }).click();
  await page.getByRole("button", { name: /Open Potential account compromise/ }).first().click();
  await page.getByRole("tab", { name: "Notes", exact: true }).click();
  const note = `Evidence reviewed during acceptance ${Date.now()}.`;
  await page.getByLabel("Add a note").fill(note);
  await page.getByRole("button", { name: "Add note", exact: true }).click();
  await expect(page.getByText(note, { exact: true })).toBeVisible();
  const report = page.waitForEvent("download");
  await page.getByRole("button", { name: "Generate report" }).click();
  expect((await report).suggestedFilename()).toMatch(/^RPT-/);
  await page.getByRole("navigation").getByRole("button", { name: "Threat Hunting", exact: true }).click();
  await page.getByLabel("Hunting query").fill('outcome = "failure"');
  await page.getByRole("button", { name: "Run query", exact: true }).click();
  await expect(page.getByText(/\d+ matching events/)).toBeVisible();
  await expect(page.locator("tbody tr").first()).toBeVisible();
  await page.getByRole("navigation").getByRole("button", { name: "Detection Rules", exact: true }).click();
  await page.getByRole("button", { name: /Open / }).first().click();
  await page.getByRole("button", { name: "Validate", exact: true }).click();
  await expect(page.locator("pre").filter({ hasText: '"valid": true' })).toBeVisible();
  await page.getByRole("navigation").getByRole("button", { name: "Settings", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Integrations & delivery" })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Notification delivery queue" })).toBeVisible();
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Sign in to your workspace" })).toBeVisible();
});
