def make_synthetic_attack_chain(base_time: datetime) -> list[dict]:
    """Build an attack sequence that triggers AEGIS-CORR-001 and contains all observable types."""
    common = {"host": "WORKSTATION-01", "source_ip": "192.168.1.100", "username": "target-admin"}
    raw_events: list[dict] = []

    # 1. 12 failed authentication attempts (triggers AEGIS-AUTH-001)
    for _ in range(12):
        raw_events.append(common | {
            "event_category": "authentication",
            "action": "login",
            "outcome": "failure",
            "message": "Failed authentication attempt",
        })

    # 2. 1 successful privileged login (triggers AEGIS-AUTH-003)
    raw_events.append(common | {
        "event_category": "authentication",
        "action": "login",
        "outcome": "success",
        "authentication": {"privileged": True},
        "message": "Privileged login success after failed attempts",
    })

    # 3. Privilege escalation via sudo (triggers AEGIS-PRIV-001)
    raw_events.append(common | {
        "event_category": "privilege",
        "action": "sudo",
        "outcome": "success",
        "command_line": "sudo su -",
        "message": "Privilege escalation via sudo",
    })

    # 4. Process execution with malicious hash (triggers AEGIS-PROC-001)
    raw_events.append(common | {
        "event_category": "process",
        "action": "execute",
        "process": {"name": "powershell.exe"},
        "command_line": "powershell.exe -enc dGVzdA==",
        "file": {
            "path": "C:\\Windows\\Temp\\payload.exe",
            "hash": "a" * 64,
            "sha256": "a" * 64,
        },
        "message": "Synthetic encoded PowerShell process telemetry",
    })

    # 5. Outbound network connection with malicious & unknown domains, url, and public IP (triggers AEGIS-NET-003 and completes CORR-001)
    raw_events.append(common | {
        "event_category": "network",
        "action": "connect",
        "destination_ip": "203.0.113.10",
        "destination_port": 443,
        "http": {
            "domain": "malicious.example.test",
            "url": "https://malicious.example.test/payload.bin?auth=token123#dl",
        },
        "network": {
            "domain": "unknown.example.org",
        },
        "message": "Outbound C2 connection to external IP",
    })

    return [
        {
            "source": "aegis-simulator",
            "source_type": "json",
            "collector": "synthetic",
            "timestamp": (base_time + timedelta(seconds=idx * 5)).isoformat(),
            "source_sequence": f"{base_time.isoformat()}:e2e-attack:{idx}",
            "raw_event": raw,
        }
        for idx, raw in enumerate(raw_events)
    ]


def test_end_to_end_ioc_detection_incident_storyline_soar(system):
    """Full E2E verification through real API endpoints and worker processors."""
    client = system["client"]
    settings = system["settings"]
    settings.intel_mock_enabled = True
    base_time = datetime.now(UTC) - timedelta(minutes=5)

    synthetic_payloads = make_synthetic_attack_chain(base_time)

    # 1. Ingest events via public API
    ingest_resp = client.post("/api/v1/events/ingest", json={"events": synthetic_payloads})
    assert ingest_resp.status_code == 202, ingest_resp.text
    assert len(ingest_resp.json()["accepted"]) == len(synthetic_payloads)

    # 2. Pipeline processing (Worker drain: Detection -> Alerts -> Incidents -> Extraction)
    drain(system)

    # Verify alerts were generated by detection rules
    alerts_resp = client.get("/api/v1/alerts")
    assert alerts_resp.status_code == 200
    alerts = alerts_resp.json()["items"]
    assert len(alerts) > 0, "Expected alerts from synthetic attack sequence"
    alert_rules = {a["rule_id"] for a in alerts}
    assert {"AEGIS-AUTH-001", "AEGIS-AUTH-003", "AEGIS-PRIV-001", "AEGIS-PROC-001", "AEGIS-CORR-001"} <= alert_rules

    # Verify incident was created automatically by correlation
    incidents_resp = client.get("/api/v1/incidents")
    assert incidents_resp.status_code == 200
    incidents = incidents_resp.json()["items"]
    assert len(incidents) == 1, f"Expected 1 incident, found {len(incidents)}"
    incident = incidents[0]
    incident_id = incident["id"]

    # Verify attack storyline correlation
    storyline_resp = client.post("/api/v1/storylines/correlate?window_seconds=3600")
    assert storyline_resp.status_code == 200, storyline_resp.text
    assert storyline_resp.json()["storylines"] >= 1
    storylines = client.get("/api/v1/storylines").json()["items"]
    assert len(storylines) >= 1
    storyline_id = storylines[0]["id"]

    # 3. Verify observable extraction and evidence integrity
    # Extraction must NOT alter raw events or fabricate evidence
    with system["app"].state.sessions() as db:
        events = list(db.scalars(select(EventRecord).where(EventRecord.organization_id == system["org"])))
        for ev in events:
            assert ev.intel_indexed is True
            # Verify original raw event structure is intact
            assert "source_ip" in ev.payload
        observables = list(db.scalars(select(Observable).where(Observable.organization_id == system["org"])))
        obs_values = {o.value for o in observables}
        assert "203.0.113.10" in obs_values
        assert "malicious.example.test" in obs_values
        assert "a" * 64 in obs_values
        assert "unknown.example.org" in obs_values
        assert "192.168.1.100" in obs_values

        # Check URL normalization stripped token & fragment:
        assert "https://malicious.example.test/payload.bin" in obs_values
        assert "token123" not in str(obs_values)

        # Check private IP external_allowed is False
        priv_obs = next(o for o in observables if o.value == "192.168.1.100")
        assert priv_obs.external_allowed is False

        # Check ObservableEvent links exist
        links = list(db.scalars(select(ObservableEvent).where(ObservableEvent.organization_id == system["org"])))
        assert len(links) > 0

    # 4. Analyst investigation: Verify intelligence context is attached to incident
    investigation_resp = client.get(f"/api/v1/investigations/{incident_id}")
    assert investigation_resp.status_code == 200
    inv = investigation_resp.json()
    assert "intelligence" in inv
    # Verify raw events in investigation evidence are not rewritten
    for ev in inv["evidence"]:
        assert "source_ip" in ev["event"]

    # 5. Enrich observables through source enrichment
    enrich_source_resp = client.post(
        "/api/v1/iocs/enrich-source",
        json={"source_type": "incident", "source_id": incident_id, "provider": "mock"},
    )
    assert enrich_source_resp.status_code == 200, enrich_source_resp.text
    source_items = enrich_source_resp.json()["items"]
    assert len(source_items) > 0

    # Notification worker executes lookup
    completed_lookups = lookup_once(settings, system["app"].state.sessions)
    assert completed_lookups > 0

    # Verify verdicts from mock provider
    ctx_resp = client.get(f"/api/v1/iocs/source-context/incident/{incident_id}")
    assert ctx_resp.status_code == 200
    ctx_items = {item["value"]: item for item in ctx_resp.json()["items"]}

    assert "malicious.example.test" in ctx_items
    assert ctx_items["malicious.example.test"]["verdict"] == "malicious"
    assert ctx_items["malicious.example.test"]["assessment_origin"] == "mock"
    assert ctx_items["malicious.example.test"]["confidence"] == 90

    assert "a" * 64 in ctx_items
    assert ctx_items["a" * 64]["verdict"] == "suspicious"

    assert "unknown.example.org" in ctx_items
    assert ctx_items["unknown.example.org"]["verdict"] == "unknown"

    # Private IP remains unknown
    if "192.168.1.100" in ctx_items:
        assert ctx_items["192.168.1.100"]["verdict"] == "unknown"

    # Also verify source context on Storyline
    story_ctx = client.get(f"/api/v1/iocs/source-context/storyline/{storyline_id}")
    assert story_ctx.status_code == 200
    assert len(story_ctx.json()["items"]) > 0

    # 6. SOAR Playbook lifecycle and execution
    # Find observable ID for malicious domain
    malicious_obs_id = next(
        item["observable"]["id"]
        for item in source_items
        if item["observable"]["value"] == "malicious.example.test"
    )

    # Ensure IP entity exists for simulated containment target
    with system["app"].state.sessions.begin() as db:
        ip_entity = db.scalar(
            select(Entity).where(Entity.organization_id == system["org"], Entity.value == "203.0.113.10")
        )
        if not ip_entity:
            ip_entity = Entity(organization_id=system["org"], type="ip", value="203.0.113.10")
            db.add(ip_entity)
            db.flush()
        ip_entity_id = ip_entity.id

    # Create SOAR playbook definition
    playbook_doc = {
        "description": "End-to-End SOC response workflow",
        "trigger": {
            "source": "incident",
            "conditions": [{"field": "severity", "op": "gte", "value": "medium"}],
            "required_fields": ["severity", "status"],
            "required_evidence_fields": ["source_ip"],
        },
        "input_schema": {
            "observable_id": "observable",
            "target_id": "entity",
        },
        "timeout_seconds": 300,
        "steps": [
            {"id": "enrich_step", "action": "enrich_observable", "provider": "mock"},
            {
                "id": "note_step",
                "action": "incident_note",
                "when": {"field": "intel_verdict", "op": "eq", "value": "malicious"},
                "on_false": "summary_step",
            },
            {"id": "contain_step", "action": "simulate_block_ip"},
            {"id": "summary_step", "action": "summary"},
        ],
    }

    # Validate definition
    val_resp = client.post("/api/v1/soar/validate", json=playbook_doc)
    assert val_resp.status_code == 200
    assert val_resp.json()["valid"] is True

    # Save playbook as SECURITY_ADMIN
    client.headers["Authorization"] = "Bearer " + system["tokens"]["SECURITY_ADMIN"]
    pb_resp = client.post(
        "/api/v1/soar/playbooks",
        json={"name": "E2E Investigation Response", "definition": playbook_doc, "enabled": True},
    )
    assert pb_resp.status_code == 200, pb_resp.text
    playbook = pb_resp.json()
    playbook_id = playbook["id"]

    # 7. Execute playbook as SENIOR_ANALYST (requires playbooks.execute + incidents.update)
    client.headers["Authorization"] = "Bearer " + system["tokens"]["SENIOR_ANALYST"]
    run_req = {
        "source_type": "incident",
        "source_id": incident_id,
        "inputs": {"observable_id": malicious_obs_id, "target_id": ip_entity_id},
        "dry_run": False,
        "idempotency_key": "e2e-playbook-exec-key-001",
    }
    exec_resp = client.post(f"/api/v1/soar/playbooks/{playbook_id}/execute", json=run_req)
    assert exec_resp.status_code == 200, exec_resp.text
    run_id = exec_resp.json()["id"]

    # Advance worker: Steps 1 & 2 execute; Step 3 hits containment requiring approval
    for _ in range(3):
        process_workflows(settings, system["app"].state.sessions)

    run_detail = client.get(f"/api/v1/soar/executions/{run_id}").json()
    assert run_detail["status"] == "WAITING_FOR_APPROVAL"
    assert len(run_detail["history"]) >= 2
    # Verify incident note was added because intel_verdict was malicious
    assert run_detail["history"][1]["output"]["data"]["note_added"] is True

    with system["app"].state.sessions() as db:
        notes = list(db.scalars(select(CaseNote).where(CaseNote.organization_id == system["org"])))
        assert any("Advisory intelligence" in n.text for n in notes)

    # 8. Test approval security:
    # A. Self-approval by requester (SENIOR_ANALYST) MUST be rejected (403)
    dec_path = f"/api/v1/soar/executions/{run_id}/decision"
    self_appr = client.post(dec_path, json={"decision": "approve"})
    assert self_appr.status_code == 403, "Self-approval must be rejected"

    # B. Cross-tenant approval attempt by OUTSIDER MUST return 404
    client.headers["Authorization"] = "Bearer " + system["tokens"]["OUTSIDER"]
    outsider_appr = client.post(dec_path, json={"decision": "approve"})
    assert outsider_appr.status_code == 404, "Cross-tenant access must return 404"

    # C. Legitimate approval by independent SOC_MANAGER
    client.headers["Authorization"] = "Bearer " + system["tokens"]["SOC_MANAGER"]
    mgr_appr = client.post(dec_path, json={"decision": "approve"})
    assert mgr_appr.status_code == 200, mgr_appr.text

    # Worker advances remaining steps
    process_workflows(settings, system["app"].state.sessions)
    process_workflows(settings, system["app"].state.sessions)

    final_run = client.get(f"/api/v1/soar/executions/{run_id}").json()
    assert final_run["status"] == "SUCCEEDED", final_run

    # Verify containment action remained explicitly simulated
    contain_history = next(h for h in final_run["history"] if h["step"] == "contain_step")
    assert contain_history["output"]["simulated"] is True
    assert contain_history["output"]["external_changed"] is False
    assert "Simulation only" in contain_history["output"]["data"]["message"]

    # 9. Test Idempotency: repeated execution returns identical run
    client.headers["Authorization"] = "Bearer " + system["tokens"]["SENIOR_ANALYST"]
    dup_resp = client.post(f"/api/v1/soar/playbooks/{playbook_id}/execute", json=run_req)
    assert dup_resp.status_code == 200
    assert dup_resp.json()["id"] == run_id

    # 10. Verify audit integrity
    with system["app"].state.sessions() as db:
        assert verify_audit(db, settings, system["org"]) is True
        audit_events = list(db.scalars(
            select(AuditLog.action).where(AuditLog.organization_id == system["org"])
        ))
        assert "soar.queued" in audit_events
        assert "soar.approval_required" in audit_events
        assert "soar.approve" in audit_events
        assert "soar.simulated" in audit_events
        assert "soar.succeeded" in audit_events


def test_missing_or_unknown_enrichment_does_not_satisfy_malicious_verdict(system):
    """Negative safety test: unknown or un-enriched IOC must never satisfy malicious branch."""
    client = system["client"]
    settings = system["settings"]
    settings.intel_mock_enabled = True

    with system["app"].state.sessions.begin() as db:
        obs = observe(db, system["org"], "domain", "benign.example.org")
        incident = Incident(organization_id=system["org"], title="Benign Inc", severity="medium")
        db.add(incident)
        db.flush()
        obs_id, inc_id = obs.id, incident.id

    playbook_doc = {
        "description": "Safe branching on unknown intelligence",
        "trigger": {"source": "incident"},
        "input_schema": {"observable_id": "observable"},
        "steps": [
            {"id": "intel", "action": "enrich_observable", "provider": "mock"},
            {
                "id": "malicious_note",
                "action": "incident_note",
                "when": {"field": "intel_verdict", "op": "eq", "value": "malicious"},
                "on_false": "summary",
            },
            {"id": "summary", "action": "summary"},
        ],
    }

    client.headers["Authorization"] = "Bearer " + system["tokens"]["SECURITY_ADMIN"]
    pb = client.post(
        "/api/v1/soar/playbooks",
        json={"name": "Safety Branching", "definition": playbook_doc, "enabled": True},
    ).json()

    client.headers["Authorization"] = "Bearer " + system["tokens"]["SENIOR_ANALYST"]
    run = client.post(
        f"/api/v1/soar/playbooks/{pb['id']}/execute",
        json={
            "source_type": "incident",
            "source_id": inc_id,
            "inputs": {"observable_id": obs_id},
            "dry_run": False,
            "idempotency_key": "safe-branch-001",
        },
    ).json()

    # Step 1: enrich_observable -> queues mock provider
    process_workflows(settings, system["app"].state.sessions)
    # Worker performs lookup -> unknown for benign.example.org
    lookup_once(settings, system["app"].state.sessions)
    # Clear wait backoff
    with system["app"].state.sessions.begin() as db:
        db.get(WorkflowRun, run["id"]).available_at = 0
    # Workflows advance (Step 0: intel completes, Step 1: malicious_note skips, Step 2: summary executes)
    for _ in range(3):
        process_workflows(settings, system["app"].state.sessions)

    detail = client.get(f"/api/v1/soar/executions/{run['id']}").json()
    assert detail["status"] == "SUCCEEDED"
    # Step malicious_note MUST be SKIPPED
    steps_status = {h["step"]: h["status"] for h in detail["history"]}
    assert steps_status["intel"] == "SUCCEEDED"
    assert steps_status["malicious_note"] == "SKIPPED"
    assert steps_status["summary"] == "SUCCEEDED"

    # Prove no case notes were added
    with system["app"].state.sessions() as db:
        notes = list(db.scalars(select(CaseNote).where(
            CaseNote.organization_id == system["org"],
            CaseNote.resource_id == inc_id,
        )))
        assert len(notes) == 0


def test_provider_outage_does_not_suppress_detections_or_events(system, monkeypatch):
    """Resilience test: intelligence provider outage/timeout does not affect detection pipeline."""
    client = system["client"]

    class CrashingProvider:
        def lookup(self, settings, observable):
            raise ConnectionError("External threat feed offline")

    monkeypatch.setitem(PROVIDERS, "virustotal", CrashingProvider())
    monkeypatch.setitem(PROVIDERS, "mock", CrashingProvider())

    # Ingest synthetic events that trigger detection rules and correlation into an incident
    base_time = datetime.now(UTC) - timedelta(minutes=5)
    synthetic_payloads = make_synthetic_attack_chain(base_time)

    ingest_resp = client.post("/api/v1/events/ingest", json={"events": synthetic_payloads})
    assert ingest_resp.status_code == 202

    # Drain worker: event detection and extraction proceed without crashing
    drain(system)

    # Alerts and incidents are still created!
    alerts = client.get("/api/v1/alerts").json()["items"]
    assert any(a["rule_id"] == "AEGIS-AUTH-001" for a in alerts)
    assert any(a["rule_id"] == "AEGIS-CORR-001" for a in alerts)
    incidents = client.get("/api/v1/incidents").json()["items"]
    assert len(incidents) >= 1


def test_security_rbac_and_cross_tenant_boundaries(system):
    """Security test: strict RBAC enforcement and absolute tenant isolation."""
    client = system["client"]

    # 1. VIEWER cannot execute mutations
    client.headers["Authorization"] = "Bearer " + system["tokens"]["VIEWER"]
    assert client.post("/api/v1/iocs/enrich", json={
        "observable": {"type": "ip", "value": "8.8.8.8"}
    }).status_code == 403
    assert client.post("/api/v1/soar/playbooks", json={
        "name": "Unauthorized", "definition": {"description": "x", "trigger": {"source": "incident"}, "steps": []}
    }).status_code == 403

    # 2. ANALYST cannot write playbooks
    client.headers["Authorization"] = "Bearer " + system["tokens"]["ANALYST"]
    assert client.post("/api/v1/soar/playbooks", json={
        "name": "Unauthorized2", "definition": {"description": "x", "trigger": {"source": "incident"}, "steps": []}
    }).status_code == 403

    # 3. SENIOR_ANALYST cannot approve playbooks
    client.headers["Authorization"] = "Bearer " + system["tokens"]["SENIOR_ANALYST"]
    assert client.post("/api/v1/soar/executions/nonexistent/decision", json={"decision": "approve"}).status_code == 403

    # 4. Cross-tenant IDOR: OUTSIDER cannot see primary tenant resources
    client.headers["Authorization"] = "Bearer " + system["tokens"]["SECURITY_ADMIN"]
    created_pb = client.post("/api/v1/soar/playbooks", json={
        "name": "Tenant-A-Playbook",
        "definition": {
            "description": "Tenant A workflow",
            "trigger": {"source": "incident"},
            "steps": [{"id": "summary", "action": "summary"}],
        },
        "enabled": True,
    }).json()

    client.headers["Authorization"] = "Bearer " + system["tokens"]["OUTSIDER"]
    assert client.get(f"/api/v1/soar/playbooks/{created_pb['id']}").status_code == 404
    assert client.get("/api/v1/soar/playbooks").json()["items"] == []
